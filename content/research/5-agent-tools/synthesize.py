def call(prompt):
    body = json.dumps({"model": MODEL, "max_tokens": int(os.environ.get("MAX_TOKENS", "20000")), "system": SYSTEM,
                       "messages": [{"role": "user", "content": prompt}]}).encode()
    req = urllib.request.Request(BASE.rstrip("/") + "/v1/messages", data=body, headers={
        "x-api-key": KEY, "anthropic-version": "2023-06-01", "content-type": "application/json"})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(req, timeout=400) as r:
                d = json.load(r)
            return "".join(b.get("text", "") for b in d["content"]), d.get("usage", {})
        except Exception:
            if attempt == 3:
                raise
            time.sleep(8 * (attempt + 1))


if __name__ == "__main__":
    module, src, out = sys.argv[1:4]
    data = open(src, encoding="utf-8").read()[:350000]
    text, usage = call(BRIEFS[module] + "\n\nالبيانات:\n" + data)
    open(out, "w", encoding="utf-8").write(text)
    print(module, usage)
