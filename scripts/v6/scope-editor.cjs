/**
 * Scope the v6 site-editor stylesheet (the editor sample's own CSS, copied
 * unchanged into editor-source.css with its two spring curves filled in) under
 * .v6e, so it can run inside the real editor without touching anything
 * outside it. Same recipe as scope-v6.cjs, for the editor's file.
 *
 *   node scripts/v6/scope-editor.cjs   →   components/editor/v6/editor.css
 *
 * What changes, and nothing else:
 *   :root            → .v6e (the tokens)
 *   body             → .v6e (ground, ink, face)
 *   :root.dk / [data-theme=dark] → html.dash-dk .v6e (the dashboard's own dark switch)
 *   the "follow the device" dark block is dropped: useDashTheme already
 *   turns html.dash-dk on and off with the device.
 *   html,body and html{} are dropped: the editor is a fixed layer, not the page.
 *   keyframes get a v6e- prefix so they cannot meet another sheet's.
 */
const fs = require('fs')
const path = require('path')
const postcss = require('postcss')

const src = fs.readFileSync(path.join(__dirname, 'editor-source.css'), 'utf8')
const root = postcss.parse(src)

const frames = new Set()
root.walkAtRules('keyframes', (a) => { frames.add(a.params); a.params = 'v6e-' + a.params })
root.walkAtRules('media', (a) => {
  if (/prefers-color-scheme\s*:\s*dark/.test(a.params)) a.remove()
})

const S = '.v6e'
function scope(sel) {
  sel = sel.trim()
  if (sel === ':root') return S
  if (sel === ':root[data-theme="dark"]') return 'html.dash-dk ' + S
  if (sel.startsWith(':root.dk')) return 'html.dash-dk ' + S + sel.slice(':root.dk'.length)
  if (sel === 'html') return null
  if (sel === 'body') return S
  return S + ' ' + sel
}

root.walkRules((r) => {
  if (r.parent && r.parent.type === 'atrule' && /keyframes$/.test(r.parent.name)) return
  if (r.selector.trim() === 'html,body') { r.remove(); return }
  const out = r.selectors.map(scope).filter(Boolean)
  if (!out.length) { r.remove(); return }
  r.selectors = out
})

root.walkDecls(/^animation(-name)?$/, (d) => {
  d.value = d.value.split(',').map((part) =>
    part.trim().split(/\s+/).map((w) => (frames.has(w) ? 'v6e-' + w : w)).join(' ')).join(', ')
})

const head = '/* GENERATED by scripts/v6/scope-editor.cjs from scripts/v6/editor-source.css (the editor sample\'s own stylesheet). Do not edit; edit the source or editor-frame.css. */\n'
fs.writeFileSync(path.join(__dirname, '../../components/editor/v6/editor.css'), head + root.toString())
console.log('frames', [...frames].join(' '))
