/**
 * Scope the v6 dashboard stylesheet (the design file's own CSS, copied
 * unchanged into v6-source.css) under .v6, so it can run inside the real
 * dashboard without touching anything outside it.
 *
 *   node scripts/v6/scope-v6.cjs   →   components/app/v6/v6.css
 *
 * What changes, and nothing else:
 *   :root            → .v6 (the tokens)
 *   body             → .v6 (ground, ink, face)
 *   :root.dk / [data-theme=dark] → html.dash-dk .v6 (the dashboard's own dark switch)
 *   the "follow the device" dark block is dropped: useDashTheme already
 *   turns html.dash-dk on and off with the device.
 *   @font-face is dropped (dash-theme.ts declares the same faces).
 *   keyframes get a v6- prefix so they cannot meet another sheet's.
 *   ::view-transition(root) is left to the dashboard's own theme curtain.
 *   nothing reaches into an older screen's section.page.legacy (guard below).
 */
const fs = require('fs')
const path = require('path')
const postcss = require('postcss')

const src = fs.readFileSync(path.join(__dirname, 'v6-source.css'), 'utf8')
const root = postcss.parse(src)

const frames = new Set()
root.walkAtRules('keyframes', (a) => { frames.add(a.params); a.params = 'v6-' + a.params })
root.walkAtRules('font-face', (a) => a.remove())
root.walkAtRules('media', (a) => {
  if (/prefers-color-scheme\s*:\s*dark/.test(a.params)) a.remove()
})

const S = '.v6'
function scope(sel) {
  sel = sel.trim()
  if (sel.startsWith('::view-transition')) return /\(root\)/.test(sel) ? null : sel
  if (sel === ':root') return S
  if (sel === ':root[data-theme="dark"]') return 'html.dash-dk ' + S
  if (sel.startsWith(':root.dk')) return 'html.dash-dk ' + S + sel.slice(':root.dk'.length)
  if (sel.startsWith(':root:not(.dk)')) return 'html:not(.dash-dk) ' + S + sel.slice(':root:not(.dk)'.length)
  if (sel === 'html' || sel === 'body') return sel === 'body' ? S : 'html.dash-on'
  if (sel.startsWith('html.')) { const i = sel.indexOf(' '); return sel.slice(0, i) + ' ' + S + sel.slice(i) }
  return S + ' ' + sel
}

/**
 * The older screens render inside the frame too (section.page.legacy), and
 * the design's element rules — `.v6 button{padding:0;background:none}`,
 * `.v6 p{margin:0}` — outrank their Tailwind classes. So every rule about
 * something inside .v6 skips anything inside a legacy page: the guard goes
 * on the rule's subject (its last compound, before any ::pseudo-element),
 * wrapped in :where() so it adds no weight and v6-frame.css still wins.
 */
const GUARD = ':where(:not(.legacy *))'
function guard(sel) {
  const at = sel.indexOf(S + ' ')
  if (at < 0) return sel
  let depth = 0, last = at + S.length
  for (let i = at + S.length; i < sel.length; i++) {
    const c = sel[i]
    if (c === '(' || c === '[') depth++
    else if (c === ')' || c === ']') depth--
    else if (!depth && (c === ' ' || c === '>' || c === '+' || c === '~')) last = i
  }
  const tail = sel.slice(last)
  let pe = -1
  depth = 0
  for (let i = 0; i < tail.length - 1; i++) {
    const c = tail[i]
    if (c === '(' || c === '[') depth++
    else if (c === ')' || c === ']') depth--
    else if (!depth && c === ':' && tail[i + 1] === ':') { pe = i; break }
  }
  const cut = pe < 0 ? sel.length : last + pe
  return sel.slice(0, cut) + GUARD + sel.slice(cut)
}

root.walkRules((r) => {
  if (r.parent && r.parent.type === 'atrule' && /keyframes$/.test(r.parent.name)) return
  if (r.selector.trim() === 'html,body') { r.remove(); return }
  const out = r.selectors.map(scope).filter(Boolean).map(guard)
  if (!out.length) { r.remove(); return }
  r.selectors = out
})

root.walkDecls(/^animation(-name)?$/, (d) => {
  d.value = d.value.split(',').map((part) =>
    part.trim().split(/\s+/).map((w) => (frames.has(w) ? 'v6-' + w : w)).join(' ')).join(', ')
})

const head = '/* GENERATED by scripts/v6/scope-v6.cjs from scripts/v6/v6-source.css (the v6 design file\'s own stylesheet). Do not edit; edit the source or v6-frame.css. */\n'
fs.writeFileSync(path.join(__dirname, '../../components/app/v6/v6.css'), head + root.toString())
console.log('frames', [...frames].join(' '))
