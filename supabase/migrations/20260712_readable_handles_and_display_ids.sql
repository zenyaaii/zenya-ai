-- ────────────────────────────────────────────────────────────────────────
-- 3. Overview views — for one-click Supabase Studio browsing.
--     No UUIDs in the primary columns; UUIDs kept as trailing "id" for
--     when you need to join out to the raw tables.
-- ────────────────────────────────────────────────────────────────────────

drop view if exists public.admin_users_overview;
create view public.admin_users_overview
with (security_invoker = true) as
select
  p.member_no                                    as "#",
  p.handle                                       as "handle",
  coalesce(p.full_name, split_part(p.email, '@', 1)) as "name",
  p.email                                        as "email",
  p.plan                                         as "plan",
  p.is_pro                                       as "pro",
  p.has_hosting                                  as "hosting",
  p.trial_themes_used || '/' || p.trial_themes_limit as "trial",
  p.pro_purchased_at                             as "paid_at",
  p.last_seen_at                                 as "last_seen",
  p.created_at                                   as "joined",
  p.id                                           as "user_uuid"
from public.profiles p
order by p.member_no asc;

comment on view public.admin_users_overview is
  'Human-readable users list — # + handle + email + tier — ordered by member_no. '
  'UUID kept as trailing column for cross-table lookups. Founder browsing view.';

drop view if exists public.admin_themes_overview;
create view public.admin_themes_overview
with (security_invoker = true) as
select
  t.display_no                                   as "#",
  p.member_no                                    as "user_#",
  p.handle                                       as "user",
  t.product_name                                 as "name",
  t.template_type                                as "template",
  case
    when t.is_published and t.slug is not null then 'live · /s/' || t.slug
    when t.template_type in ('one_product','storefront','collective') then 'shopify export'
    else 'draft'
  end                                            as "status",
  t.view_count                                   as "views",
  t.created_at                                   as "created",
  t.id                                           as "theme_uuid"
from public.themes t
left join public.profiles p on p.id = t.user_id
order by t.display_no desc;

comment on view public.admin_themes_overview is
  'Human-readable themes list — # + owner handle + name + status. Newest first.';

-- Grant read on the overview views to authenticated (RLS on the underlying
-- profiles/themes tables still governs what each user sees — service_role
-- sees everything, users only see their own).
grant select on public.admin_users_overview   to authenticated, service_role;
grant select on public.admin_themes_overview  to authenticated, service_role;
